package com.example.cloud

import android.content.Context
import android.util.Log
import com.example.ai.configureAppCheck
import com.google.firebase.FirebaseApp
import com.google.firebase.FirebaseOptions
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import org.json.JSONObject

private const val TAG = "FirebaseRuntimeConfig"
private const val PREFS_NAME = "jarvis_firebase_runtime_cfg"
private const val KEY_APP_ID = "app_id"
private const val KEY_API_KEY = "api_key"
private const val KEY_PROJECT_ID = "project_id"
private const val KEY_STORAGE_BUCKET = "storage_bucket"
private const val KEY_GCM_SENDER_ID = "gcm_sender_id"
private const val KEY_WEB_CLIENT_ID = "default_web_client_id"

data class ParsedGoogleServicesConfig(
    val projectId: String,
    val applicationId: String,
    val apiKey: String,
    val storageBucket: String?,
    val gcmSenderId: String?,
    val defaultWebClientId: String?
)

/**
 * Gerencia a inicialização segura do Firebase tanto a partir do google-services.json
 * embutido em tempo de compilação quanto de um google-services.json importado pelo usuário
 * em compilações externas (como builds de CI / F-Droid sem secrets configurados).
 */
object FirebaseRuntimeConfig {

    private val _configRevision = MutableStateFlow(0)
    val configRevision: StateFlow<Int> = _configRevision.asStateFlow()

    @Synchronized
    fun ensureFirebaseInitialized(context: Context): Boolean {
        val appContext = context.applicationContext
        if (FirebaseApp.getApps(appContext).isNotEmpty()) {
            return true
        }

        // 1) Try standard build-time resources generated by google-services Gradle plugin
        val defaultApp = runCatching { FirebaseApp.initializeApp(appContext) }.getOrNull()
        if (defaultApp != null || FirebaseApp.getApps(appContext).isNotEmpty()) {
            return true
        }

        // 2) Fallback: load user-imported google-services.json stored privately on device
        val saved = readSavedConfig(appContext) ?: return false
        return initializeFromConfig(appContext, saved)
    }

    fun isFirebaseAvailable(context: Context): Boolean {
        return ensureFirebaseInitialized(context)
    }

    fun resolveDefaultWebClientId(context: Context): String? {
        val appContext = context.applicationContext
        val resId = appContext.resources.getIdentifier(
            "default_web_client_id",
            "string",
            appContext.packageName
        )
        if (resId != 0) {
            val fromRes = runCatching { appContext.getString(resId) }
                .getOrNull()
                ?.takeIf { it.isNotBlank() }
            if (fromRes != null) return fromRes
        }
        return readSavedConfig(appContext)?.defaultWebClientId?.takeIf { it.isNotBlank() }
    }

    fun getActiveProjectId(context: Context): String? {
        val appContext = context.applicationContext
        if (ensureFirebaseInitialized(appContext)) {
            val fromApp = runCatching { FirebaseApp.getInstance().options.projectId }.getOrNull()
            if (!fromApp.isNullOrBlank()) return fromApp
        }
        return readSavedConfig(appContext)?.projectId
    }

    fun hasImportedRuntimeConfig(context: Context): Boolean {
        return readSavedConfig(context.applicationContext) != null
    }

    @Synchronized
    fun importGoogleServicesJson(context: Context, rawJson: String): Result<String> {
        val appContext = context.applicationContext
        val parsed = parseGoogleServicesJson(rawJson, appContext.packageName)
            .getOrElse { return Result.failure(it) }

        val prefs = appContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit()
            .putString(KEY_PROJECT_ID, parsed.projectId)
            .putString(KEY_APP_ID, parsed.applicationId)
            .putString(KEY_API_KEY, parsed.apiKey)
            .putString(KEY_STORAGE_BUCKET, parsed.storageBucket.orEmpty())
            .putString(KEY_GCM_SENDER_ID, parsed.gcmSenderId.orEmpty())
            .putString(KEY_WEB_CLIENT_ID, parsed.defaultWebClientId.orEmpty())
            .commit()

        val initialized = if (FirebaseApp.getApps(appContext).isNotEmpty()) {
            true
        } else {
            initializeFromConfig(appContext, parsed)
        }

        if (!initialized) {
            return Result.failure(IllegalStateException("Não foi possível inicializar o Firebase com os dados informados."))
        }

        runCatching { configureAppCheck(appContext, null) }
        _configRevision.value = _configRevision.value + 1
        return Result.success(parsed.projectId)
    }

    fun parseGoogleServicesJson(rawJson: String, packageName: String): Result<ParsedGoogleServicesConfig> {
        return runCatching {
            val root = JSONObject(rawJson.trim())
            val projectInfo = root.optJSONObject("project_info")
                ?: throw IllegalArgumentException("Campo project_info ausente no google-services.json.")

            val projectId = projectInfo.optString("project_id").trim()
            val gcmSenderId = projectInfo.optString("project_number").trim().ifBlank { null }
            val storageBucket = projectInfo.optString("storage_bucket").trim().ifBlank { null }

            val clients = root.optJSONArray("client")
                ?: throw IllegalArgumentException("Campo client ausente no google-services.json.")
            if (clients.length() == 0) {
                throw IllegalArgumentException("Nenhum cliente Android encontrado no google-services.json.")
            }

            // Prefer client matching our exact package name; fallback to first valid Android client
            var selectedClient: JSONObject? = null
            for (i in 0 until clients.length()) {
                val c = clients.optJSONObject(i) ?: continue
                val pkg = c.optJSONObject("client_info")
                    ?.optJSONObject("android_client_info")
                    ?.optString("package_name")
                    ?.trim()
                if (pkg == packageName) {
                    selectedClient = c
                    break
                }
                if (selectedClient == null) selectedClient = c
            }

            val client = selectedClient
                ?: throw IllegalArgumentException("Cliente Android inválido no google-services.json.")

            val appId = client.optJSONObject("client_info")
                ?.optString("mobilesdk_app_id")
                ?.trim()
                .orEmpty()

            val apiKeyArray = client.optJSONArray("api_key")
            val apiKey = (0 until (apiKeyArray?.length() ?: 0))
                .asSequence()
                .mapNotNull { idx -> apiKeyArray?.optJSONObject(idx)?.optString("current_key")?.trim() }
                .firstOrNull { it.isNotBlank() }
                .orEmpty()

            var webClientId: String? = null
            val oauthClients = client.optJSONArray("oauth_client")
            if (oauthClients != null) {
                for (i in 0 until oauthClients.length()) {
                    val oc = oauthClients.optJSONObject(i) ?: continue
                    if (oc.optInt("client_type") == 3) {
                        val cid = oc.optString("client_id").trim()
                        if (cid.isNotBlank()) {
                            webClientId = cid
                            break
                        }
                    }
                }
            }
            if (webClientId == null) {
                val otherOauth = client.optJSONObject("services")
                    ?.optJSONObject("appinvite_service")
                    ?.optJSONArray("other_platform_oauth_client")
                if (otherOauth != null) {
                    for (i in 0 until otherOauth.length()) {
                        val oc = otherOauth.optJSONObject(i) ?: continue
                        if (oc.optInt("client_type") == 3) {
                            val cid = oc.optString("client_id").trim()
                            if (cid.isNotBlank()) {
                                webClientId = cid
                                break
                            }
                        }
                    }
                }
            }

            require(projectId.isNotBlank()) { "project_id ausente no google-services.json." }
            require(appId.isNotBlank()) { "mobilesdk_app_id ausente no google-services.json." }
            require(apiKey.isNotBlank()) { "api_key.current_key ausente no google-services.json." }

            ParsedGoogleServicesConfig(
                projectId = projectId,
                applicationId = appId,
                apiKey = apiKey,
                storageBucket = storageBucket,
                gcmSenderId = gcmSenderId,
                defaultWebClientId = webClientId
            )
        }
    }

    private fun readSavedConfig(appContext: Context): ParsedGoogleServicesConfig? {
        val prefs = appContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val projectId = prefs.getString(KEY_PROJECT_ID, "").orEmpty().trim()
        val appId = prefs.getString(KEY_APP_ID, "").orEmpty().trim()
        val apiKey = prefs.getString(KEY_API_KEY, "").orEmpty().trim()
        if (projectId.isBlank() || appId.isBlank() || apiKey.isBlank()) return null

        return ParsedGoogleServicesConfig(
            projectId = projectId,
            applicationId = appId,
            apiKey = apiKey,
            storageBucket = prefs.getString(KEY_STORAGE_BUCKET, "")?.trim()?.ifBlank { null },
            gcmSenderId = prefs.getString(KEY_GCM_SENDER_ID, "")?.trim()?.ifBlank { null },
            defaultWebClientId = prefs.getString(KEY_WEB_CLIENT_ID, "")?.trim()?.ifBlank { null }
        )
    }

    private fun initializeFromConfig(
        appContext: Context,
        config: ParsedGoogleServicesConfig
    ): Boolean {
        return runCatching {
            val builder = FirebaseOptions.Builder()
                .setApplicationId(config.applicationId)
                .setApiKey(config.apiKey)
                .setProjectId(config.projectId)
            config.storageBucket?.let { builder.setStorageBucket(it) }
            config.gcmSenderId?.let { builder.setGcmSenderId(it) }
            FirebaseApp.initializeApp(appContext, builder.build())
            Log.i(TAG, "Firebase initialized dynamically for project=${config.projectId}")
            true
        }.onFailure { err ->
            Log.e(TAG, "Dynamic FirebaseApp initialization failed", err)
        }.getOrDefault(false)
    }
}
